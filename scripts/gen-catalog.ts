/**
 * npm run catalog — generates the block + kind catalog the build-course skill reads
 * (skills/build-course/catalog.md) from every registry entry's docs, schema and example,
 * and refreshes the catalog section of docs/content-format.md. Never edit those sections by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { z } from "zod";
import { withApp, ROOT } from "./lib/app";

type JsonSchema = { type?: string | string[]; properties?: Record<string, JsonSchema>; required?: string[]; items?: JsonSchema; anyOf?: JsonSchema[]; enum?: unknown[]; default?: unknown; description?: string; prefixItems?: JsonSchema[]; const?: unknown; additionalProperties?: JsonSchema | boolean };

const typeOf = (s: JsonSchema | undefined): string => {
  if (!s) return "any";
  if (s.enum) return s.enum.map((e) => JSON.stringify(e)).join(" \\| ");
  if (s.anyOf) return s.anyOf.map(typeOf).join(" \\| ");
  if (s.prefixItems) return `[${s.prefixItems.map(typeOf).join(", ")}]`;
  if (s.type === "array") return `${typeOf(s.items)}[]`;
  if (s.type === "object" && s.properties) return "object";
  if (s.type === "object") return "map";
  return Array.isArray(s.type) ? s.type.join(" \\| ") : s.type ?? "any";
};

function fieldsTable(schema: JsonSchema): string {
  const target = schema.anyOf?.find((x) => x.type === "object") ?? schema;
  if (target.type !== "object" || !target.properties) return `Props: \`${typeOf(schema)}\`${schema.anyOf ? " (shorthand form accepted)" : ""}\n`;
  const rows = Object.entries(target.properties).map(([k, v]) => {
    const req = target.required?.includes(k) && v.default === undefined ? "yes" : "";
    const def = v.default !== undefined ? `\`${JSON.stringify(v.default)}\`` : "";
    return `| \`${k}\` | \`${typeOf(v)}\` | ${req} | ${def} |`;
  });
  return `| field | type | required | default |\n|---|---|---|---|\n${rows.join("\n")}\n${schema.anyOf ? "\nA shorthand (non-object) form is also accepted.\n" : ""}`;
}

const md = await withApp(({ blockRegistry, kindRegistry }) => {
  const blocks = blockRegistry.list().sort((a, b) => a.group.localeCompare(b.group) || a.type.localeCompare(b.type));
  const groups = [...new Set(blocks.map((b) => b.group))];
  let out = `<!-- GENERATED by \`npm run catalog\` from the block and kind registries. Do not edit by hand. -->\n\n`;
  out += `## Blocks\n\nA body item is \`{ node: … }\` or exactly one block \`{ <type>: <props> }\`. Blocks nest only inside layout blocks.\n\n`;
  out += `| block | group | ruler | reads/writes vars |\n|---|---|---|---|\n`;
  for (const b of blocks) out += `| [\`${b.type}\`](#block-${b.type}) | ${b.group} | ${b.ruler === "snap" ? "snapped" : "line holder"}${b.card ? ", card" : ""} | ${b.reads || b.writes ? `${b.reads ? "reads" : ""}${b.reads && b.writes ? " / " : ""}${b.writes ? "writes" : ""}` : ""} |\n`;
  for (const g of groups) {
    out += `\n### ${g[0]!.toUpperCase()}${g.slice(1)}\n`;
    for (const b of blocks.filter((x) => x.group === g)) {
      let js: JsonSchema = {};
      try {
        js = z.toJSONSchema(b.schema, { io: "input", unrepresentable: "any" }) as JsonSchema;
      } catch {
        /* unrepresentable */
      }
      out += `\n<a id="block-${b.type}"></a>\n#### \`${b.type}\` (v${b.version})\n\n${b.docs.trim()}\n\n${fieldsTable(js)}\nExample:\n\n\`\`\`yaml\n${b.example.trim()}\n\`\`\`\n`;
    }
  }
  out += `\n## Node kinds\n\n\`kind\` on a node. Containers have no checkbox state of their own (fully derived from children).\n\n| kind | label (es / en) | heading | container by default | extra fields |\n|---|---|---|---|---|\n`;
  for (const k of kindRegistry.list()) {
    let extra = "";
    if (k.fields) {
      try {
        const js = z.toJSONSchema(k.fields, { io: "input", unrepresentable: "any" }) as JsonSchema;
        extra = Object.keys(js.properties ?? {}).map((f) => `\`${f}\``).join(", ");
      } catch {
        extra = "(see docs)";
      }
    }
    out += `| \`${k.kind}\` | ${k.label.es ?? ""} / ${k.label.en ?? ""} | ${k.heading} | ${k.container ? "yes" : ""} | ${extra} |\n`;
  }
  out += `\n${kindRegistry.list().map((k) => `- **\`${k.kind}\`**: ${k.docs}`).join("\n")}\n`;
  return out;
});

const header = `# Block & kind catalog\n\nThe vocabulary the build-course skill writes content with. Generated from the registries in\n\`app/src/blocks/\` and \`app/src/kinds/\`; regenerate with \`npm run catalog\` after adding or changing one.\nFull file format: \`docs/content-format.md\`.\n\n`;
writeFileSync(resolve(ROOT, "skills/build-course/catalog.md"), header + md);

const docPath = resolve(ROOT, "docs/content-format.md");
const doc = readFileSync(docPath, "utf8");
const START = "<!-- catalog:start -->", END = "<!-- catalog:end -->";
if (doc.includes(START) && doc.includes(END)) {
  writeFileSync(docPath, doc.slice(0, doc.indexOf(START) + START.length) + "\n" + md.replace(/^## /gm, "### ").replace(/^### (Blocks|Node kinds)/gm, "### $1") + "\n" + doc.slice(doc.indexOf(END)));
}
console.log("catalog → skills/build-course/catalog.md and docs/content-format.md");
